"""``gen3-fields``: rules/GEN3-FIELDS.md, each canonical field with the rules it serves."""

from collections import Counter

from .gen3_lines import learnable_today
from .gen3_registry import requirement_closure
from .locations import RULES

_COLUMNS = ["slot", "shape", "source", "what"]


def _alone_ids(ids, entries):
    """The ids that, with what they require, are the rule's whole change."""

    def closure(i):
        return requirement_closure(entries, {i})

    def is_whole_change(i):
        subsumed = any(ids <= closure(j) for j in ids if j != i and i in closure(j))
        return ids <= closure(i) and not subsumed

    return [i for i in ids if is_whole_change(i)]


def _usage(entries, rows):
    """``(serves, alone)``: per id, the rules that need it and the rules it alone settles."""
    serves, alone = Counter(), Counter()
    for r in rows:
        ids = set(r["gen3_inputs"] + r["gen3_outputs"] + r["gen3_fixes"])
        serves.update(ids)
        if not r["gen3_dropped"]:
            alone.update(_alone_ids(ids, entries))
    return serves, alone


def _header(reg, rows):
    now = sum(1 for r in rows if learnable_today(r))
    after = sum(1 for r in rows if r["learnable_after_gen3"])
    out = ["# Gen-3 inputs and outputs", "",
           "Generated by `python scripts/rules_catalogue.py gen3-fields` from "
           "`rules/gen3-fields.json` and `rules/heads/`; do not edit by hand. Each rule's line "
           "in `rules/heads/<unit>.jsonl` carries `gen3_inputs`, `gen3_outputs`, `gen3_fixes`, "
           "`gen3_dropped` and `learnable_after_gen3`.", "",
           f"Rules: {len(rows)}. Learnable today: {now}. Learnable once every field, extension, "
           f"planned item and fix below is in: {after}. "
           f"Left out by a dropped name: {len(rows) - after}.", "",
           "Columns: rules = rules that need it, counting the rules that need it through another "
           "entry's requires; alone = rules for which it, with what it requires, is the whole "
           "change needed.", "",
           "## Conventions", ""]
    out += [f"- **{k.replace('_', ' ')}.** {v}" for k, v in reg["conventions"].items()] + [""]
    return out, now, after


class _Tables:
    """The summary's tables, each row counting the rules it serves and alone settles."""

    def __init__(self, serves, alone):
        self.serves = serves
        self.alone = alone

    def table(self, title, items, cols):
        out = [f"## {title} ({len(items)})", "",
               "| id | " + " | ".join(cols) + " | rules | alone |",
               "|---|" + "---|" * len(cols) + "---:|---:|"]
        for e in sorted(items, key=lambda e: -self.serves[e["id"]]):
            cells = " | ".join(str(e.get(c, "")) for c in cols)
            rid = e["id"]
            out.append(f"| `{rid}` | {cells} | {self.serves[rid]} | {self.alone[rid]} |")
        out.append("")
        return out

    def all(self, reg):
        return [
            *self.table("New inputs", reg["inputs"], _COLUMNS),
            *self.table("New outputs", reg["outputs"], _COLUMNS),
            *self.table("Extensions of existing inputs and outputs", reg["extensions"],
                        ["applies_to", "what"]),
            *self.table("Already planned in the gen-3 design record", reg["planned"], ["what"]),
            *self.table("Collection and curation fixes", reg["fixes"], ["what"]),
        ]


def _dropped_lines(reg, rows):
    out = ["## Dropped names", "", "| reason | names | rules |", "|---|---|---:|"]
    for group in reg["dropped"]:
        hit = sum(1 for r in rows if set(r["gen3_dropped"]) & set(group["names"]))
        names = ", ".join(f"`{n}`" for n in group["names"])
        out.append(f"| {group['reason']} | {names} | {hit} |")
    out += [f"| {o['reason']} ({o['rule']}) | `{o['name']}` | 1 |"
            for o in reg["overrides"] if o["to"] is None]
    out.append("")
    return out


def write_gen3_summary(reg, entries, rows, rules_dir=RULES):
    """rules/GEN3-FIELDS.md: each canonical field, with the rules it serves."""
    out, now, after = _header(reg, rows)
    out += _Tables(*_usage(entries, rows)).all(reg)
    out += _dropped_lines(reg, rows)
    (rules_dir / "GEN3-FIELDS.md").write_text("\n".join(out), encoding="utf-8", newline="\n")
    print(f"learnable today {now}, after gen-3 {after}, of {len(rows)}")
