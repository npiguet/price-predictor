"""``status``: rules/STATUS.md from the sidecars."""

import re
from collections import Counter

from .locations import RULES
from .ordering import unit_sort_key
from .reading import load_rules, load_unit, units_with_sizes
from .triage import needs_scenario

CATEGORY_ORDER = ("mechanical", "legality", "decision", "definitional", "out_of_scope")


def _unit_titles():
    """``unit -> title`` from the rows of cr/index.md."""
    title = {}
    for line in (RULES / "cr" / "index.md").read_text(encoding="utf-8").splitlines():
        cells = [c.strip() for c in line.split("|")]
        if len(cells) > 3 and re.match(r"\d{3}", cells[1]):
            title[cells[1]] = cells[2]
    return title


class _Tally:
    """What the status totals count over the units' triage and scenario files."""

    def __init__(self):
        self.cat_total, self.kind_total = Counter(), Counter()
        self.n_tri = self.n_scen = self.n_pairs = 0

    def add(self, tri, doc):
        if tri:
            self.cat_total.update(r["category"] for r in tri)
        if tri is not None:
            self.n_tri += 1
        if doc:
            self.n_scen += 1
            self.n_pairs += len(doc["scenarios"])
            self.kind_total.update(s["record_kind"] for s in doc["scenarios"])


def _marks(tri, doc):
    """The triage, scenario and verified check marks of a unit."""
    want = sum(1 for r in tri if needs_scenario(r)) if tri else 0
    tri_mark = "x" if tri is not None else " "
    scen_mark = "x" if doc is not None else ("–" if tri is not None and want == 0 else " ")
    ver_mark = "x" if doc and doc.get("verified") else ("–" if scen_mark == "–" else " ")
    return tri_mark, scen_mark, ver_mark


def _row(head, tri, doc):
    """One unit's table row; ``head`` holds its first three cells."""
    cats = Counter(r["category"] for r in tri) if tri else Counter()
    tri_mark, scen_mark, ver_mark = _marks(tri, doc)
    cat_str = " ".join(f"{c[:4]}{cats[c]}" for c in CATEGORY_ORDER if cats[c])
    n_scenarios = len(doc["scenarios"]) if doc else 0
    return (f"{head} [{tri_mark}] "
            f"| [{scen_mark}] | [{ver_mark}] | {cat_str} | {n_scenarios} |")


def _status_lines(tally, n_units, rows):
    return ["# Rules catalogue status", "",
            "Generated by `python scripts/rules_catalogue.py status`; do not edit by hand.", "",
            f"Units triaged: {tally.n_tri}/{n_units}. Units with scenarios: {tally.n_scen}. "
            f"Scenarios: {tally.n_pairs}.", "",
            "Rules by category: "
            + ", ".join(f"{k} {v}" for k, v in tally.cat_total.most_common()) + ".", "",
            "Scenarios by record kind: "
            + (", ".join(f"{k} {v}" for k, v in tally.kind_total.most_common()) or "none")
            + ".", "",
            "Columns: triage, scenarios (– = no rule in the unit needs one), verified.", "",
            "| unit | title | rules | triage | scen | verified | categories | scenarios |",
            "|---|---|---|---|---|---|---|---|"] + rows


def cmd_status(_args):
    _, counts = units_with_sizes(load_rules())
    titles = _unit_titles()
    tally, rows = _Tally(), []
    for unit in sorted(counts, key=unit_sort_key):
        tri, doc = load_unit("triage", unit), load_unit("scenarios", unit)
        tally.add(tri, doc)
        rows.append(_row(f"| {unit} | {titles.get(unit, '')} | {counts[unit]} |", tri, doc))
    out = _status_lines(tally, len(counts), rows)
    (RULES / "STATUS.md").write_text("\n".join(out) + "\n", encoding="utf-8", newline="\n")
    print(f"triaged {tally.n_tri}/{len(counts)}, scenario units {tally.n_scen}, "
          f"scenarios {tally.n_pairs}")
